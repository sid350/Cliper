import AppKit

/// Polls `NSPasteboard.general` for changes (macOS has no change notification)
/// and reports new text or images.
///
/// Content marked as confidential or transient by other apps (password
/// managers, etc.) is ignored, following the conventions at nspasteboard.org.
final class PasteboardMonitor {
    enum Content {
        case text(String)
        case image(Data, NSPasteboard.PasteboardType)
    }

    /// Called on the main thread for each new clipboard entry.
    var onContent: ((Content) -> Void)?

    /// Larger entries are skipped so a huge copy can't bloat the history.
    var maxTextLength = 1_000_000          // UTF-8 bytes
    var maxImageSize = 30 * 1024 * 1024    // bytes

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ].map { NSPasteboard.PasteboardType($0) })

    private let pasteboard: NSPasteboard
    /// -1 so that whatever is on the clipboard at launch is captured once.
    private var lastChangeCount = -1
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func start(interval: TimeInterval = 0.5) {
        stop()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer.tolerance = interval * 0.2
        // .common keeps polling while menus or the popover are being tracked.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right after the app itself writes to the pasteboard, so that write
    /// isn't recorded as a new entry.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard let types = pasteboard.types, !types.isEmpty else { return }
        if types.contains(where: { Self.ignoredTypes.contains($0) }) { return }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if text.utf8.count <= maxTextLength {
                onContent?(.text(text))
            }
            return
        }

        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                if data.count <= maxImageSize {
                    onContent?(.image(data, type))
                }
                return
            }
        }
    }
}
